class UiText:
    """Attribute access to localized UI strings for templates: {{ ui.login }}."""

    def __init__(self, language: str):
        self._language = language if language in STRINGS else DEFAULT
        self._table = STRINGS[self._language]
        self._fallback = STRINGS[DEFAULT]

    def __getattr__(self, key: str) -> str:
        if key.startswith("_"):
            raise AttributeError(key)
        return self._table.get(key) or self._fallback.get(key, key)


def t(language: str | None, key: str, **kwargs: Any) -> str:
    lang = language if language in STRINGS else DEFAULT
    text = STRINGS[lang].get(key) or STRINGS[DEFAULT].get(key, key)
    if kwargs:
        try:
            return text.format(**kwargs)
        except (KeyError, ValueError):
            return text
    return text


def catalog_for(language: str | None, keys: list[str] | None = None) -> dict[str, str]:
    lang = language if language in STRINGS else DEFAULT
    source = STRINGS[lang]
    fallback = STRINGS[DEFAULT]
    if keys is None:
        keys = list(fallback.keys())
    return {key: source.get(key) or fallback.get(key, key) for key in keys}


